GRANT SELECT ON BD_ENQUETE.* TO 'mariafernanda'@'localhost';
GRANT UPDATE ON BD_ENQUETE.RESPOSTAS TO 'mariafernanda'@'localhost';

-- 4. REVOGAR UMA PERMISSÃO 
REVOKE UPDATE ON BD_ENQUETE.RESPOSTAS FROM 'mariafernanda'@'localhost';

